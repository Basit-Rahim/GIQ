"""
Step 4 - Collect every number cited in the paper into outputs/summary.md.

    python scripts/summarise.py

Reads only the outputs of steps 1-3 and the anonymised survey table.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src import config as C
from src.data import load_training_table


def _load(name):
    return json.loads((C.OUTPUTS_DIR / name).read_text())


def main():
    df = load_training_table()
    metrics, sample, pslm = _load("metrics.json"), _load("pslm_sample.json"), _load("pslm_validation.json")
    m = pslm["metrics"]
    n = df["n_school_age"]
    enrolled = (df[C.TARGET_COLUMN] * n).sum() / n.sum()
    unsafe = (df["route_safe"] == 0).mean()
    gap = m["children_enrolled_rate_predicted"] - m["children_enrolled_rate_actual"]

    rows = [
        ("Survey households with children aged 5–16", f"{len(df)}"),
        ("School-age children in those households", f"{int(n.sum())}"),
        ("Children enrolled (survey)", f"{enrolled:.1%}"),
        ("Households reporting an unsafe route", f"{(df['route_safe'] == 0).sum()} ({unsafe:.1%})"),
        ("Households with fewer than half their children enrolled", f"{metrics['not_enrolled_households']}"),
        ("PSLM Lahore households with children aged 5–16", f"{sample['households_used']}"),
        ("PSLM Lahore children aged 5–16", f"{sample['school_age_children']}"),
        ("PSLM children enrolled (observed)", f"{m['children_enrolled_rate_actual']:.1%}"),
        ("Model estimate, routes 50% unsafe", f"{m['children_enrolled_rate_predicted']:.1%}"),
        ("Difference, model minus observed (points)", f"{100 * gap:+.1f}"),
        ("Model estimate, all routes safe / all unsafe",
         f"{m['children_enrolled_rate_predicted_all_routes_safe']:.1%} / "
         f"{m['children_enrolled_rate_predicted_all_routes_unsafe']:.1%}"),
        ("AUC on PSLM households", f"{m['auc']:.3f}"),
        ("Cross-validated AUC (survey)", f"{metrics['stage2']['full_model']['auc']:.3f}"),
    ]
    lines = ["# Numbers cited in the paper", "",
             "Generated by `scripts/summarise.py` from the outputs of steps 1–3.", "",
             "| Item | Value |", "|---|---|"] + [f"| {k} | {v} |" for k, v in rows]
    (C.OUTPUTS_DIR / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
